-- Las cuotas se comparten entre instancias. La IP se almacena como hash con sal.
CREATE TABLE IF NOT EXISTS public.api_rate_limits (
  key text PRIMARY KEY,
  window_start timestamptz NOT NULL,
  attempts integer NOT NULL
);

CREATE INDEX IF NOT EXISTS api_rate_limits_window
  ON public.api_rate_limits(window_start);

ALTER TABLE public.api_rate_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.api_rate_limits FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.api_rate_limits TO service_role;

CREATE OR REPLACE FUNCTION public.consume_rate_limit(
  p_key text,
  p_limit integer,
  p_window_seconds integer
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  count_attempts integer;
BEGIN
  IF char_length(p_key) > 160
    OR p_limit NOT BETWEEN 1 AND 1000
    OR p_window_seconds NOT BETWEEN 1 AND 3600
  THEN
    RAISE EXCEPTION 'Invalid quota';
  END IF;

  DELETE FROM public.api_rate_limits
  WHERE window_start < now() - interval '1 day';

  INSERT INTO public.api_rate_limits AS q (key, window_start, attempts)
  VALUES (p_key, clock_timestamp(), 1)
  ON CONFLICT (key) DO UPDATE SET
    attempts = CASE
      WHEN q.window_start < clock_timestamp() - make_interval(secs => p_window_seconds)
        THEN 1
      ELSE least(q.attempts + 1, p_limit + 1)
    END,
    window_start = CASE
      WHEN q.window_start < clock_timestamp() - make_interval(secs => p_window_seconds)
        THEN clock_timestamp()
      ELSE q.window_start
    END
  RETURNING attempts INTO count_attempts;

  RETURN count_attempts <= p_limit;
END;
$$;

REVOKE ALL ON FUNCTION public.consume_rate_limit(text, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_rate_limit(text, integer, integer)
  TO service_role;

COMMIT;
